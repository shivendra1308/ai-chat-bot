# 01-variables.py
# Python vs JavaScript comparison

# ===== VARIABLES =====
# JavaScript: let name = "Shivendra"
name = "Shivendra"

# JavaScript: let age = 25
age = 25

# JavaScript: let is_developer = true
is_developer = True

# JavaScript: let salary = 50000.50
salary = 50000.50

# ===== PRINT (console.log) =====
# JavaScript: console.log(name)
print(name)
print(age)
print(is_developer)
print(salary)

# ===== F-STRINGS (template literals) =====
# JavaScript: `Hello ${name}, you are ${age} years old`
print(f"Hello {name}, you are {age} years old")

# ===== MULTIPLE VALUES =====
print(f"Developer: {is_developer}, Salary: {salary}")